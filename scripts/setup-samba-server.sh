#!/usr/bin/env bash

# ==============================================================================
# Sambryx - Host Server Setup & Dynamic Sudo Configuration
# ==============================================================================
# Prepare the Ubuntu/Debian host for
# administration through the Sambryx web interface:
# 1. Check root privileges.
# 2. Create a dedicated administrator account (default: admin).
# 3. Install Samba, Winbind, Kerberos and required utilities.
# 4. Allow the required executables without a password in /etc/sudoers.d/,
#    using absolute system paths to avoid PATH substitution.
# ==============================================================================

set -euo pipefail

# Terminal output colors
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m'

log_info() {
    echo -e "${GREEN}[INFO]${NC} $1"
}

log_warn() {
    echo -e "${YELLOW}[WARNING]${NC} $1"
}

log_error() {
    echo -e "${RED}[ERROR]${NC} $1" >&2
}

# 1. Check root privileges
if [ "$EUID" -ne 0 ]; then
    log_error "Run this script as root using sudo."
    exit 1
fi

PERMISSIONS_ONLY=false
if [ "${1:-}" = --permissions-only ]; then
    PERMISSIONS_ONLY=true
    shift
fi
ADMIN_USER="${1:-admin}"

# Validate: username must only contain safe characters (alphanumeric, dash, underscore, dot)
if ! echo "$ADMIN_USER" | grep -qE '^[a-z_][a-z0-9_.-]{0,31}$'; then
    log_error "Invalid username: '$ADMIN_USER'. Must match ^[a-z_][a-z0-9_.-]{0,31}$"
    exit 1
fi

SUDOERS_FILE="/etc/sudoers.d/sambryx-${ADMIN_USER}"

echo "========================================================"
echo "    Sambryx Server Setup"
echo "========================================================"
log_info "Administrator account: $ADMIN_USER"

if [ "$PERMISSIONS_ONLY" = true ]; then
    if ! id "$ADMIN_USER" >/dev/null 2>&1; then
        log_error "The administrator account must already exist for --permissions-only."
        exit 1
    fi
else
    # 2. Create the account if it does not exist
    if id "$ADMIN_USER" >/dev/null 2>&1; then
        log_info "User $ADMIN_USER already exists."
    else
        log_info "Creating user $ADMIN_USER..."
        useradd -m -s /bin/bash "$ADMIN_USER"
        echo "Set a password for user $ADMIN_USER:"
        passwd "$ADMIN_USER"
    fi

    # 3. Update package lists and install Samba
    log_info "Checking and installing required packages..."
    apt-get update -y
    apt-get install -y samba smbclient winbind krb5-user libpam-winbind libnss-winbind sudo

fi

# Resolve the absolute path of an executable.
resolve_cmd() {
    which "$1" 2>/dev/null || true
}

# ==================================================================
# PERMISSIONS (Samba administration tools)
# Allow executable access without argument restrictions,
# as the Java backend uses dynamic flags such as --.
# ==================================================================
DYNAMIC_COMMANDS=(
  systemctl pdbedit net tee testparm
  useradd userdel chpasswd smbpasswd
  groupadd groupdel gpasswd
  smbstatus df du tail kill find
  cat mv mkdir cp rm chmod chown mktemp ln
)

SUDO_ENTRIES=()
for cmd in "${DYNAMIC_COMMANDS[@]}"; do
    bin_path=$(resolve_cmd "$cmd")
    if [ -n "$bin_path" ]; then
        SUDO_ENTRIES+=("$bin_path")
    else
        case "$cmd" in
            mktemp|ln|testparm|tee|cp|mv|rm)
                log_error "Required configuration executable is missing: $cmd"
                exit 1
                ;;
        esac
    fi
done

# Join executable paths with commas
SUDO_LINE="$(IFS=', '; echo "${SUDO_ENTRIES[*]}")"

# Validate the replacement before publishing it.
STAGED_POLICY=$(mktemp /etc/sudoers.d/.sambryx-policy.XXXXXX)
trap 'rm -f -- "$STAGED_POLICY"' EXIT
cat <<EOF > "$STAGED_POLICY"
# Automatically generated by setup-samba-server.sh
# Sambryx permissions (user: $ADMIN_USER)
$ADMIN_USER ALL=(ALL) NOPASSWD: $SUDO_LINE
EOF

# Restrict sudoers file permissions as required by sudo
chmod 0440 "$STAGED_POLICY"
visudo -c -f "$STAGED_POLICY" >/dev/null
mv -T -- "$STAGED_POLICY" "$SUDOERS_FILE"

echo "========================================================"
echo " Setup completed successfully!"
echo " You can now connect to this server"
echo " through Sambryx using account: $ADMIN_USER"
echo "========================================================"
